-- 原因：V20261121122426 按“数量/总量”规则回填为“个”，但这 8 条的梳理表预警阈值
--       描述的是金额（“金额合计”“费用”“存折金额总值”“取款金额总值”），单位应为“元”。
-- 依据：运营指标体系梳理-8个维度-补充编码.xlsx 第 5 张表“预警阈值”列文本。
-- 范围：仅这 8 条，且只在当前单位仍为“个”时更新（幂等，不覆盖人工修改）。
-- 不改：阈值、条件、告警策略、采集配置、历史数据。
