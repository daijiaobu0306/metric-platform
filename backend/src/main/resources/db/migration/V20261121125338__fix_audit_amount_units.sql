START TRANSACTION;

UPDATE metric_item
   SET unit = '元', update_time = NOW(6)
 WHERE unit = '个'
   AND metric_code IN (
    'BOSS15',
    'BOSS38',
    'BOSS39',
    'BOSS40',
    'BOSS41',
    'BOSS44',
    'ZT_ZQ_006',
    'ZT_ZQ_007');

