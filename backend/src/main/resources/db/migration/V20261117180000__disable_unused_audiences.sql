-- =============================================================================
-- 岗位字典：暂时停用「网格长」「直销人员」
-- =============================================================================
-- 依据（2026-11-17 用户确认）：
--   业务梳理表（运营指标体系梳理-8个维度-20260929）的「面向人员」列没有给
--   网格长、直销人员打标签，本次角色功能验收不涉及这两个岗位范围。
--
-- 做法：
--   * 只把 status 置 0，不删字典行、不动任何指标标签，可随时改回 1 恢复；
--   * 人员视角/专屏下拉只取 status=1 的岗位，停用后这两个岗位不再出现在页面；
--   * 下方有一条防御更新：如果将来又有指标挂到这两个岗位上，自动恢复启用，
--     避免指标从所有岗位视图里消失（数据比"干净的下拉"更重要）。
-- =============================================================================

UPDATE `metric_audience`
   SET `status` = 0
 WHERE `audience_code` IN ('grid_leader', 'direct_sales');

UPDATE `metric_audience` a
   SET a.`status` = 1
 WHERE a.`audience_code` IN ('grid_leader', 'direct_sales')
   AND EXISTS (SELECT 1 FROM `metric_item` i WHERE i.`audience_code` = a.`audience_code`);
